#!/usr/bin/env node
/**
 * Generates ../src/spec/spdx-license-ids.ts from the
 * `spdx-license-ids` (CC0-1.0) and `spdx-exceptions` (CC-BY-3.0) packages.
 *
 * Identifiers and their deprecation flag only. No licence texts, no
 * obligations, no categories: BSI TR-03183-2 §6.1 requires licences to be
 * stated as SPDX identifiers or expressions, and checking that needs the
 * list of identifiers and nothing else. Anything beyond validity would be an
 * interpretation this viewer deliberately does not make.
 *
 * Run after bumping the source packages:  node packages/core/scripts/extract-license-ids.mjs
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));

const ids = require('spdx-license-ids');
const deprecated = require('spdx-license-ids/deprecated.json');
const exceptions = require('spdx-exceptions');
const deprecatedExceptions = require('spdx-exceptions/deprecated.json');
const idsVersion = require('spdx-license-ids/package.json').version;
const exceptionsVersion = require('spdx-exceptions/package.json').version;

const sorted = (list) => [...new Set(list)].sort((a, b) => a.localeCompare(b, 'en'));
const lines = (list) => list.map((id) => `  ${JSON.stringify(id)},`).join('\n');

const out = `/**
 * SPDX License List identifiers. GENERATED by scripts/extract-license-ids.mjs
 * from spdx-license-ids@${idsVersion} (CC0-1.0) and spdx-exceptions@${exceptionsVersion}
 * (CC-BY-3.0, see NOTICE). Do not edit by hand.
 *
 * Identifiers and deprecation flags only: enough to say whether a licence
 * field holds a valid SPDX identifier (BSI TR-03183-2 §6.1), and nothing that
 * would let this viewer rate a licence.
 */

const LICENSE_IDS: ReadonlySet<string> = new Set([
${lines(sorted(ids))}
]);

const DEPRECATED_LICENSE_IDS: ReadonlySet<string> = new Set([
${lines(sorted(deprecated))}
]);

const EXCEPTION_IDS: ReadonlySet<string> = new Set([
${lines(sorted(exceptions))}
]);

const DEPRECATED_EXCEPTION_IDS: ReadonlySet<string> = new Set([
${lines(sorted(deprecatedExceptions))}
]);

export const SPDX_LICENSE_LIST_SOURCE = 'spdx-license-ids@${idsVersion}';

/** Current or deprecated licence identifier on the SPDX License List (case-sensitive, as the list is). */
export function isKnownLicenseId(id: string): boolean {
  return LICENSE_IDS.has(id) || DEPRECATED_LICENSE_IDS.has(id);
}

export function isDeprecatedLicenseId(id: string): boolean {
  return DEPRECATED_LICENSE_IDS.has(id);
}

/** Current or deprecated exception identifier (the operand of WITH). */
export function isKnownExceptionId(id: string): boolean {
  return EXCEPTION_IDS.has(id) || DEPRECATED_EXCEPTION_IDS.has(id);
}

export function isDeprecatedExceptionId(id: string): boolean {
  return DEPRECATED_EXCEPTION_IDS.has(id);
}
`;

const target = resolve(here, '../src/spec/spdx-license-ids.ts');
writeFileSync(target, out);
console.log(
  `wrote ${target}: ${ids.length} ids (${deprecated.length} deprecated), ${exceptions.length} exceptions (${deprecatedExceptions.length} deprecated)`,
);
