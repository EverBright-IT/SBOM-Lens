#!/usr/bin/env node
/**
 * Generates ../src/spec/cdx-crypto-registry.ts from the CycloneDX
 * Cryptography Registry (https://cyclonedx.org/registry/cryptography/),
 * vendored under scripts/data/cyclonedx/ as published at
 * https://cyclonedx.org/schema/cryptography-defs.json and its schema
 * (CycloneDX/specification, Apache-2.0; see NOTICE).
 *
 * Names only: algorithm families with the primitives their variants
 * implement, and elliptic curves with their aliases. Nothing here says
 * whether an algorithm is strong; the registry is a vocabulary, and the lint
 * uses it as one (CycloneDX 1.7 `algorithmFamily` / `ellipticCurve`).
 *
 * Run after refreshing the data files:  node packages/core/scripts/extract-crypto-registry.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const defs = JSON.parse(readFileSync(resolve(here, 'data/cyclonedx/cryptography-defs.json'), 'utf8'));
const schema = JSON.parse(readFileSync(resolve(here, 'data/cyclonedx/cryptography-defs.schema.json'), 'utf8'));

const familyEnum = schema.definitions.algorithmFamiliesEnum.enum;
const curveEnum = schema.definitions.ellipticCurvesEnum.enum;

const families = defs.algorithms
  .map((a) => ({
    family: a.family,
    primitives: [...new Set((a.variant ?? []).map((v) => v.primitive).filter(Boolean))].sort(),
    inEnum: familyEnum.includes(a.family),
  }))
  .sort((a, b) => a.family.localeCompare(b.family, 'en'));

// Every spelling a BOM might use -> the canonical `category/name` enum value.
const curveAliases = new Map();
for (const group of defs.ellipticCurves) {
  for (const curve of group.curves) {
    const canonical = `${group.name}/${curve.name}`;
    const add = (spelling) => {
      if (!curveAliases.has(spelling)) curveAliases.set(spelling, canonical);
    };
    add(canonical);
    add(curve.name);
    for (const alias of curve.aliases ?? []) {
      add(`${alias.category}/${alias.name}`);
      add(alias.name);
    }
  }
}

const q = JSON.stringify;
const out = `/**
 * CycloneDX Cryptography Registry vocabulary. GENERATED by
 * scripts/extract-crypto-registry.mjs from cryptography-defs.json
 * (lastUpdated ${defs.lastUpdated}; CycloneDX/specification, Apache-2.0, see
 * NOTICE). Do not edit by hand.
 *
 * Names only: which algorithm families and elliptic curves the registry
 * knows, and which primitives a family's variants implement. Nothing here
 * rates an algorithm; that is what the profiles cite requirement sources for.
 */

export const CDX_CRYPTO_REGISTRY_SOURCE = 'cyclonedx.org/schema/cryptography-defs.json (${defs.lastUpdated.slice(0, 10)})';

export interface CryptoFamilyDef {
  family: string;
  /** Primitives the registry's variants of this family implement. */
  primitives: readonly string[];
  /** Whether the schema's algorithmFamily enum lists the family (a few registry entries are not in it). */
  inEnum: boolean;
}

const FAMILIES: ReadonlyMap<string, CryptoFamilyDef> = new Map<string, CryptoFamilyDef>([
${families.map((f) => `  [${q(f.family)}, { family: ${q(f.family)}, primitives: ${q(f.primitives)}, inEnum: ${f.inEnum} }],`).join('\n')}
]);

/** Lowercase spelling -> registry family name, built on first use so the module stays tree-shakeable. */
let familyByLower: ReadonlyMap<string, string> | undefined;
function lowerFamilies(): ReadonlyMap<string, string> {
  familyByLower ??= new Map([...FAMILIES.keys()].map((name) => [name.toLowerCase(), name]));
  return familyByLower;
}

/** The schema's ellipticCurve enum values, \`category/name\`. */
const CURVE_ENUM: ReadonlySet<string> = new Set([
${curveEnum.map((c) => `  ${q(c)},`).join('\n')}
]);

/** Every spelling (canonical, bare name, alias with or without category) -> canonical value. */
const CURVE_BY_SPELLING: ReadonlyMap<string, string> = new Map([
${[...curveAliases.entries()].map(([k, v]) => `  [${q(k)}, ${q(v)}],`).join('\n')}
]);

/** Exact registry family (the 1.7 algorithmFamily enum is case-sensitive). */
export function cryptoFamily(name: string): CryptoFamilyDef | undefined {
  return FAMILIES.get(name);
}

/** A family the registry knows under any casing, for messages and display. */
export function resolveCryptoFamily(name: string): CryptoFamilyDef | undefined {
  return FAMILIES.get(name) ?? FAMILIES.get(lowerFamilies().get(name.toLowerCase()) ?? '');
}

export function isKnownCryptoFamily(name: string): boolean {
  return FAMILIES.has(name);
}

/** Exact 1.7 ellipticCurve enum value (\`nist/P-256\`, \`brainpool/brainpoolP256r1\`). */
export function isKnownCurve(value: string): boolean {
  return CURVE_ENUM.has(value);
}

/** The canonical enum value a spelling refers to (\`P-256\`, \`prime256v1\`, \`secp256r1\` -> \`secg/secp256r1\` or its category), or undefined. */
export function canonicalCurve(spelling: string): string | undefined {
  return CURVE_BY_SPELLING.get(spelling) ?? CURVE_BY_SPELLING.get(spelling.toLowerCase()) ?? lowerLookup(spelling);
}

function lowerLookup(spelling: string): string | undefined {
  const wanted = spelling.toLowerCase();
  for (const [key, value] of CURVE_BY_SPELLING) if (key.toLowerCase() === wanted) return value;
  return undefined;
}

export const CRYPTO_FAMILY_COUNT = ${families.length};
export const CRYPTO_CURVE_COUNT = ${curveEnum.length};
`;

const target = resolve(here, '../src/spec/cdx-crypto-registry.ts');
writeFileSync(target, out);
console.log(`wrote ${target}: ${families.length} families, ${curveEnum.length} curves, ${curveAliases.size} curve spellings`);
